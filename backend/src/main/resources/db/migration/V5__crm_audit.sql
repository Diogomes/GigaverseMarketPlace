-- CRM (etiquetas e notas internas) e trilha de auditoria.

CREATE TABLE customer_tags (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(30) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX customer_tags_name_unique ON customer_tags (lower(name));

CREATE TABLE customer_tag_assignments (
    user_id      bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    tag_id       bigint      NOT NULL REFERENCES customer_tags (id) ON DELETE CASCADE,
    assigned_by  bigint REFERENCES users (id) ON DELETE SET NULL,
    assigned_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, tag_id)
);
CREATE INDEX customer_tag_assignments_tag_idx ON customer_tag_assignments (tag_id);

-- Notas internas: nunca expostas ao cliente.
CREATE TABLE customer_notes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     bigint        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    author_user_id  bigint REFERENCES users (id) ON DELETE SET NULL,
    body            varchar(2000) NOT NULL,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    updated_at      timestamptz   NOT NULL DEFAULT now(),
    deleted_at      timestamptz,
    CONSTRAINT customer_notes_body_not_blank CHECK (length(btrim(body)) > 0)
);
CREATE INDEX customer_notes_customer_idx ON customer_notes (customer_id, created_at DESC) WHERE deleted_at IS NULL;

-- Auditoria de ações relevantes. `details` não deve conter senhas, tokens nem dados de pagamento.
CREATE TABLE audit_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id  bigint REFERENCES users (id) ON DELETE SET NULL,
    action         varchar(80) NOT NULL,
    entity_type    varchar(60) NOT NULL,
    entity_id      varchar(60),
    details        jsonb,
    request_id     varchar(64),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_entity_idx ON audit_log (entity_type, entity_id, created_at DESC);
CREATE INDEX audit_log_actor_idx ON audit_log (actor_user_id, created_at DESC);
CREATE INDEX audit_log_created_idx ON audit_log (created_at);
