-- Contas, perfis, endereços, consentimentos e tokens de recuperação de senha.
-- Convenções: PK bigint identity; timestamps em timestamptz (UTC); exclusão lógica
-- (deleted_at) onde há histórico a preservar; e-mails sempre gravados em minúsculas.

CREATE TABLE users (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                  varchar(254) NOT NULL,
    password_hash          varchar(255) NOT NULL,
    full_name              varchar(120) NOT NULL,
    role                   varchar(20)  NOT NULL,
    status                 varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    email_verified_at      timestamptz,
    last_login_at          timestamptz,
    failed_login_attempts  integer      NOT NULL DEFAULT 0,
    locked_until           timestamptz,
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    deleted_at             timestamptz,
    version                bigint       NOT NULL DEFAULT 0,
    CONSTRAINT users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT users_email_format CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT users_role_valid CHECK (role IN ('CUSTOMER', 'OPERATOR', 'ADMIN')),
    CONSTRAINT users_status_valid CHECK (status IN ('ACTIVE', 'DISABLED', 'ANONYMIZED')),
    CONSTRAINT users_failed_attempts_non_negative CHECK (failed_login_attempts >= 0)
);
-- Unicidade só entre contas não excluídas (permite novo cadastro após anonimização).
CREATE UNIQUE INDEX users_email_unique ON users (email) WHERE deleted_at IS NULL;
CREATE INDEX users_role_idx ON users (role);
CREATE INDEX users_created_at_idx ON users (created_at);

CREATE TABLE customer_profiles (
    user_id      bigint PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    phone        varchar(20),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT customer_profiles_phone_format CHECK (phone IS NULL OR phone ~ '^\+?[0-9]{10,15}$')
);

-- Histórico de consentimentos (LGPD): cada concessão/revogação vira uma linha.
CREATE TABLE user_consents (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    consent_type      varchar(30) NOT NULL,
    granted           boolean     NOT NULL,
    document_version  varchar(20),
    recorded_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT user_consents_type_valid CHECK (consent_type IN ('TERMS', 'PRIVACY_POLICY', 'MARKETING_EMAIL'))
);
CREATE INDEX user_consents_user_idx ON user_consents (user_id, consent_type, recorded_at DESC);

CREATE TABLE addresses (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label           varchar(40)  NOT NULL,
    recipient_name  varchar(120) NOT NULL,
    postal_code     varchar(8)   NOT NULL,
    street          varchar(160) NOT NULL,
    number          varchar(20)  NOT NULL,
    complement      varchar(80),
    district        varchar(80)  NOT NULL,
    city            varchar(80)  NOT NULL,
    state           varchar(2)   NOT NULL,
    is_default      boolean      NOT NULL DEFAULT false,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    deleted_at      timestamptz,
    CONSTRAINT addresses_postal_code_format CHECK (postal_code ~ '^[0-9]{8}$'),
    CONSTRAINT addresses_state_format CHECK (state ~ '^[A-Z]{2}$')
);
CREATE INDEX addresses_user_idx ON addresses (user_id) WHERE deleted_at IS NULL;
-- No máximo um endereço principal ativo por usuário.
CREATE UNIQUE INDEX addresses_one_default_per_user ON addresses (user_id) WHERE is_default AND deleted_at IS NULL;

-- Guarda apenas o hash SHA-256 do token; o token em claro só existe no e-mail enviado.
CREATE TABLE password_reset_tokens (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   varchar(64) NOT NULL UNIQUE,
    expires_at   timestamptz NOT NULL,
    used_at      timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT password_reset_tokens_hash_format CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT password_reset_tokens_expiry_after_creation CHECK (expires_at > created_at),
    CONSTRAINT password_reset_tokens_used_before_expiry CHECK (used_at IS NULL OR used_at <= expires_at)
);
CREATE INDEX password_reset_tokens_user_idx ON password_reset_tokens (user_id, created_at DESC);
