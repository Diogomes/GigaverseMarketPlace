-- Estoque por produto + trilha de movimentações.
-- O saldo nunca fica negativo (CHECK); baixas usam UPDATE condicional/lock na transação (Fase 04/06).

CREATE TABLE inventory_items (
    product_id           bigint      PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE,
    quantity_on_hand     integer     NOT NULL DEFAULT 0,
    quantity_reserved    integer     NOT NULL DEFAULT 0,
    low_stock_threshold  integer     NOT NULL DEFAULT 0,
    updated_at           timestamptz NOT NULL DEFAULT now(),
    version              bigint      NOT NULL DEFAULT 0,
    CONSTRAINT inventory_on_hand_non_negative CHECK (quantity_on_hand >= 0),
    CONSTRAINT inventory_reserved_non_negative CHECK (quantity_reserved >= 0),
    CONSTRAINT inventory_reserved_within_on_hand CHECK (quantity_reserved <= quantity_on_hand),
    CONSTRAINT inventory_threshold_non_negative CHECK (low_stock_threshold >= 0)
);

CREATE TABLE stock_movements (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      bigint       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    movement_type   varchar(20)  NOT NULL,
    quantity_delta  integer      NOT NULL,
    quantity_after  integer      NOT NULL,
    reason          varchar(255),
    order_id        bigint,      -- FK adicionada em V4 (tabela orders)
    actor_user_id   bigint REFERENCES users (id) ON DELETE SET NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT stock_movements_type_valid CHECK (movement_type IN
        ('INITIAL', 'PURCHASE', 'ADJUSTMENT', 'SALE', 'RETURN', 'CANCELLATION')),
    CONSTRAINT stock_movements_delta_non_zero CHECK (quantity_delta <> 0),
    CONSTRAINT stock_movements_after_non_negative CHECK (quantity_after >= 0),
    CONSTRAINT stock_movements_adjustment_needs_reason CHECK (movement_type <> 'ADJUSTMENT' OR reason IS NOT NULL)
);
CREATE INDEX stock_movements_product_idx ON stock_movements (product_id, created_at DESC);
