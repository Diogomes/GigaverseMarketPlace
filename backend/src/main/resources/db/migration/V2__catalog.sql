-- Catálogo: categorias, produtos, opções (tamanho/acabamento) e imagens.
-- Dinheiro em numeric(12,2) com moeda explícita (somente BRL nesta versão).

CREATE TABLE categories (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         varchar(80)  NOT NULL UNIQUE,
    name         varchar(80)  NOT NULL,
    description  varchar(300),
    parent_id    bigint REFERENCES categories (id) ON DELETE RESTRICT,
    sort_order   integer      NOT NULL DEFAULT 0,
    active       boolean      NOT NULL DEFAULT true,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT categories_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT categories_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE products (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug              varchar(120)  NOT NULL UNIQUE,
    sku               varchar(32)   NOT NULL UNIQUE,
    name              varchar(120)  NOT NULL,
    description       text          NOT NULL,
    category_id       bigint        NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    product_type      varchar(20)   NOT NULL,
    status            varchar(20)   NOT NULL DEFAULT 'DRAFT',
    price             numeric(12,2) NOT NULL,
    promo_price       numeric(12,2),
    currency          varchar(3)    NOT NULL DEFAULT 'BRL',
    production_days   integer,
    weight_grams      integer,
    length_mm         integer,
    width_mm          integer,
    height_mm         integer,
    featured          boolean       NOT NULL DEFAULT false,
    seo_title         varchar(70),
    seo_description   varchar(160),
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),
    version           bigint        NOT NULL DEFAULT 0,
    -- Busca textual em português (nome pesa mais que descrição).
    search_vector     tsvector GENERATED ALWAYS AS (
        setweight(to_tsvector('portuguese', coalesce(name, '')), 'A') ||
        setweight(to_tsvector('portuguese', coalesce(description, '')), 'B')
    ) STORED,
    CONSTRAINT products_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT products_sku_format CHECK (sku ~ '^[A-Z0-9-]{3,32}$'),
    CONSTRAINT products_type_valid CHECK (product_type IN ('READY', 'MADE_TO_ORDER', 'CUSTOM')),
    CONSTRAINT products_status_valid CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    CONSTRAINT products_price_positive CHECK (price > 0),
    CONSTRAINT products_promo_price_valid CHECK (promo_price IS NULL OR (promo_price > 0 AND promo_price < price)),
    CONSTRAINT products_currency_brl CHECK (currency = 'BRL'),
    CONSTRAINT products_production_days_range CHECK (production_days IS NULL OR production_days BETWEEN 1 AND 120),
    CONSTRAINT products_production_days_required CHECK (product_type = 'READY' OR production_days IS NOT NULL),
    CONSTRAINT products_dimensions_positive CHECK (
        (weight_grams IS NULL OR weight_grams > 0) AND (length_mm IS NULL OR length_mm > 0) AND
        (width_mm IS NULL OR width_mm > 0) AND (height_mm IS NULL OR height_mm > 0))
);
CREATE INDEX products_category_idx ON products (category_id);
CREATE INDEX products_status_idx ON products (status);
CREATE INDEX products_active_featured_idx ON products (featured) WHERE status = 'ACTIVE';
CREATE INDEX products_search_idx ON products USING gin (search_vector);

-- Opções de personalização (ex.: Tamanho, Acabamento) com acréscimo de preço.
-- O estoque é controlado por produto; opções são variações produzidas sob demanda.
CREATE TABLE product_options (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   bigint      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    name         varchar(40) NOT NULL,
    sort_order   integer     NOT NULL DEFAULT 0,
    CONSTRAINT product_options_unique_name UNIQUE (product_id, name)
);

CREATE TABLE product_option_values (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_id    bigint        NOT NULL REFERENCES product_options (id) ON DELETE CASCADE,
    label        varchar(40)   NOT NULL,
    price_delta  numeric(12,2) NOT NULL DEFAULT 0,
    sort_order   integer       NOT NULL DEFAULT 0,
    CONSTRAINT product_option_values_unique_label UNIQUE (option_id, label),
    CONSTRAINT product_option_values_delta_non_negative CHECK (price_delta >= 0)
);

-- Metadados das imagens; o arquivo fica no storage (local em dev, S3 em produção).
CREATE TABLE product_images (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    bigint       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    storage_key   varchar(255) NOT NULL UNIQUE,
    alt_text      varchar(160) NOT NULL,
    content_type  varchar(20)  NOT NULL,
    size_bytes    integer      NOT NULL,
    width_px      integer,
    height_px     integer,
    sort_order    integer      NOT NULL DEFAULT 0,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT product_images_content_type_valid CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT product_images_size_limit CHECK (size_bytes > 0 AND size_bytes <= 5242880),
    CONSTRAINT product_images_dimensions_positive CHECK (
        (width_px IS NULL OR width_px > 0) AND (height_px IS NULL OR height_px > 0))
);
CREATE INDEX product_images_product_idx ON product_images (product_id, sort_order);
