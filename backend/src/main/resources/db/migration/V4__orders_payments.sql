-- Carrinho, pedidos (com snapshots), histórico de status, pagamentos e envios.

CREATE TABLE carts (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               bigint UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    anonymous_token_hash  varchar(64) UNIQUE,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    expires_at            timestamptz,
    CONSTRAINT carts_owner_required CHECK (user_id IS NOT NULL OR anonymous_token_hash IS NOT NULL),
    CONSTRAINT carts_token_hash_format CHECK (anonymous_token_hash IS NULL OR anonymous_token_hash ~ '^[0-9a-f]{64}$')
);
CREATE INDEX carts_expires_idx ON carts (expires_at) WHERE user_id IS NULL;

-- Preços NÃO são guardados no carrinho: são recalculados no servidor a cada leitura/checkout.
CREATE TABLE cart_items (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id           bigint      NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id        bigint      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    option_value_ids  bigint[]    NOT NULL DEFAULT '{}',
    quantity          integer     NOT NULL,
    added_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cart_items_quantity_range CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT cart_items_unique_line UNIQUE (cart_id, product_id, option_value_ids)
);

CREATE SEQUENCE order_number_seq START WITH 1000;

CREATE TABLE orders (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number                   bigint        NOT NULL UNIQUE DEFAULT nextval('order_number_seq'),
    user_id                  bigint        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status                   varchar(30)   NOT NULL DEFAULT 'PENDING_PAYMENT',
    currency                 varchar(3)    NOT NULL DEFAULT 'BRL',
    subtotal                 numeric(12,2) NOT NULL,
    shipping_total           numeric(12,2) NOT NULL DEFAULT 0,
    discount_total           numeric(12,2) NOT NULL DEFAULT 0,
    total                    numeric(12,2) NOT NULL,
    payment_method           varchar(10)   NOT NULL,
    shipping_method          varchar(20)   NOT NULL,
    -- Snapshot do cliente e do endereço no momento da compra (não muda se o cadastro mudar).
    customer_name            varchar(120)  NOT NULL,
    customer_email           varchar(254)  NOT NULL,
    ship_recipient_name      varchar(120),
    ship_postal_code         varchar(8),
    ship_street              varchar(160),
    ship_number              varchar(20),
    ship_complement          varchar(80),
    ship_district            varchar(80),
    ship_city                varchar(80),
    ship_state               varchar(2),
    customer_note            varchar(500),
    idempotency_key          varchar(64),
    cancellation_reason      varchar(500),
    placed_at                timestamptz   NOT NULL DEFAULT now(),
    paid_at                  timestamptz,
    cancelled_at             timestamptz,
    created_at               timestamptz   NOT NULL DEFAULT now(),
    updated_at               timestamptz   NOT NULL DEFAULT now(),
    version                  bigint        NOT NULL DEFAULT 0,
    CONSTRAINT orders_status_valid CHECK (status IN
        ('PENDING_PAYMENT', 'PAID', 'IN_PRODUCTION', 'READY_FOR_PICKUP', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT orders_currency_brl CHECK (currency = 'BRL'),
    CONSTRAINT orders_amounts_non_negative CHECK (subtotal >= 0 AND shipping_total >= 0 AND discount_total >= 0),
    CONSTRAINT orders_discount_not_above_subtotal CHECK (discount_total <= subtotal),
    CONSTRAINT orders_total_consistent CHECK (total = subtotal + shipping_total - discount_total),
    CONSTRAINT orders_payment_method_valid CHECK (payment_method IN ('PIX', 'CARD')),
    CONSTRAINT orders_shipping_method_valid CHECK (shipping_method IN ('DELIVERY', 'PICKUP')),
    CONSTRAINT orders_delivery_needs_address CHECK (shipping_method = 'PICKUP' OR (
        ship_recipient_name IS NOT NULL AND ship_postal_code IS NOT NULL AND ship_street IS NOT NULL AND
        ship_number IS NOT NULL AND ship_district IS NOT NULL AND ship_city IS NOT NULL AND ship_state IS NOT NULL)),
    CONSTRAINT orders_ship_postal_code_format CHECK (ship_postal_code IS NULL OR ship_postal_code ~ '^[0-9]{8}$'),
    CONSTRAINT orders_ship_state_format CHECK (ship_state IS NULL OR ship_state ~ '^[A-Z]{2}$'),
    CONSTRAINT orders_cancelled_has_timestamp CHECK (status <> 'CANCELLED' OR cancelled_at IS NOT NULL),
    CONSTRAINT orders_idempotency_unique UNIQUE (user_id, idempotency_key)
);
CREATE INDEX orders_user_created_idx ON orders (user_id, created_at DESC);
CREATE INDEX orders_status_created_idx ON orders (status, created_at DESC);
CREATE INDEX orders_created_idx ON orders (created_at);

