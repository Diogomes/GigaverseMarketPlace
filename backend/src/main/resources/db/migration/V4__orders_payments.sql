-- Snapshot do produto: nome, SKU, opções e preço unitário no momento da compra.
CREATE TABLE order_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        bigint        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id      bigint REFERENCES products (id) ON DELETE SET NULL,
    product_name    varchar(120)  NOT NULL,
    sku             varchar(32)   NOT NULL,
    options_summary varchar(255),
    unit_price      numeric(12,2) NOT NULL,
    quantity        integer       NOT NULL,
    line_total      numeric(12,2) NOT NULL,
    CONSTRAINT order_items_unit_price_non_negative CHECK (unit_price >= 0),
    CONSTRAINT order_items_quantity_range CHECK (quantity BETWEEN 1 AND 999),
    CONSTRAINT order_items_line_total_consistent CHECK (line_total = unit_price * quantity)
);
CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_product_idx ON order_items (product_id);

CREATE TABLE order_status_history (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            bigint      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    from_status         varchar(30),
    to_status           varchar(30) NOT NULL,
    changed_by_user_id  bigint REFERENCES users (id) ON DELETE SET NULL,
    reason              varchar(500),
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT order_status_history_changed CHECK (from_status IS NULL OR from_status <> to_status)
);
CREATE INDEX order_status_history_order_idx ON order_status_history (order_id, created_at);

-- Nunca armazena número de cartão, CVV ou validade: apenas bandeira e 4 últimos dígitos.
CREATE TABLE payments (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            bigint        NOT NULL REFERENCES orders (id) ON DELETE RESTRICT,
    provider            varchar(40)   NOT NULL,
    method              varchar(10)   NOT NULL,
    status              varchar(20)   NOT NULL DEFAULT 'PENDING',
    amount              numeric(12,2) NOT NULL,
    currency            varchar(3)    NOT NULL DEFAULT 'BRL',
    provider_reference  varchar(120),
    card_brand          varchar(20),
    card_last4          varchar(4),
    failure_reason      varchar(255),
    paid_at             timestamptz,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    version             bigint        NOT NULL DEFAULT 0,
    CONSTRAINT payments_method_valid CHECK (method IN ('PIX', 'CARD')),
    CONSTRAINT payments_status_valid CHECK (status IN
        ('PENDING', 'AUTHORIZED', 'PAID', 'FAILED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT payments_amount_positive CHECK (amount > 0),
    CONSTRAINT payments_currency_brl CHECK (currency = 'BRL'),
    CONSTRAINT payments_card_last4_format CHECK (card_last4 IS NULL OR card_last4 ~ '^[0-9]{4}$'),
    CONSTRAINT payments_card_fields_only_for_card CHECK (method = 'CARD' OR (card_brand IS NULL AND card_last4 IS NULL)),
    CONSTRAINT payments_paid_has_timestamp CHECK (status <> 'PAID' OR paid_at IS NOT NULL)
);
CREATE INDEX payments_order_idx ON payments (order_id);
CREATE UNIQUE INDEX payments_provider_reference_unique ON payments (provider, provider_reference)
    WHERE provider_reference IS NOT NULL;

-- Idempotência de webhooks: o mesmo evento do provedor só é processado uma vez.
CREATE TABLE payment_webhook_events (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider       varchar(40)  NOT NULL,
    event_id       varchar(120) NOT NULL,
    event_type     varchar(80)  NOT NULL,
    payload_sha256 varchar(64)  NOT NULL,
    received_at    timestamptz  NOT NULL DEFAULT now(),
    processed_at   timestamptz,
    CONSTRAINT payment_webhook_events_unique UNIQUE (provider, event_id)
);

CREATE TABLE shipments (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       bigint        NOT NULL REFERENCES orders (id) ON DELETE RESTRICT,
    carrier        varchar(60),
    service        varchar(60),
    tracking_code  varchar(60),
    status         varchar(20)   NOT NULL DEFAULT 'PENDING',
    cost           numeric(12,2),
    shipped_at     timestamptz,
    delivered_at   timestamptz,
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT shipments_status_valid CHECK (status IN ('PENDING', 'SHIPPED', 'DELIVERED', 'RETURNED')),
    CONSTRAINT shipments_cost_non_negative CHECK (cost IS NULL OR cost >= 0),
    CONSTRAINT shipments_delivery_after_shipping CHECK (delivered_at IS NULL OR shipped_at IS NULL OR delivered_at >= shipped_at)
);
CREATE INDEX shipments_order_idx ON shipments (order_id);
